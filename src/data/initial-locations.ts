function city(
  slug: string,
  name: string,
  district: string,
  aliases?: string[],
): SeedLocation {
  return {
    slug,
    name,
    locationType: 'city',
    parentSlug: district,
    district,
    ...(aliases ? { aliases } : {}),
  };
}

function town(slug: string, name: string, district: string): SeedLocation {
  return {
    slug,
    name,
    locationType: 'town',
    parentSlug: district,
    district,
  };
}

function area(
  slug: string,
  name: string,
  district: string,
  parentSlug: string,
): SeedLocation {
  return {
    slug,
    name,
    locationType: 'area',
    parentSlug,
    district,
  };
}

