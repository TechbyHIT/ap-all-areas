function priorityAreas(
  citySlug: string,
  districtSlug: string,
  names: string[],
): SeedLocation[] {
  return names.map((name) => {
    const slug = name
      .toLowerCase()
      .replace(/\./g, '')
      .replace(/\s+/g, '-')
      .replace(/[^a-z0-9-]/g, '');

    return {
      slug,
      name,
      locationType: 'area' as const,
      parentSlug: citySlug,
      district: districtSlug,
    };
  });
}

