export type LocationType =
  | 'state'
  | 'district'
  | 'city'
  | 'town'
  | 'area'
  | 'locality';

export interface SeedLocation {
  slug: string;
  name: string;
  locationType: LocationType;
  parentSlug?: string;
  district?: string;
  aliases?: string[];
}

export interface DistrictSeed extends SeedLocation {
  locationType: 'district';
  places: SeedLocation[];
}

export interface LocationAliasEntry {
  canonicalSlug: string;
  canonicalName: string;
  aliases: string[];
}

export interface HighPriorityCitySeed {
  citySlug: string;
  cityName: string;
  districtSlug: string;
  areas: SeedLocation[];
}

